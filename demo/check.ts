/**
 * Sends every demo scenario through a running agent and checks the result. The personas live in
 * their own repo, SafeContext/MacroHard; clone it and run its ./setup.sh first (that makes the
 * fake keys some scenarios use).
 *
 *   node demo/check.ts                      # agent on 127.0.0.1:4747, MacroHard in ~/github/MacroHard
 *   node demo/check.ts --port 4799 --dir /path/to/MacroHard
 *   node demo/check.ts --list               # print the guide; commit it to MacroHard as TRY-THESE.md
 *
 * Needs Node 24 (runs TypeScript directly).
 */
import { readdirSync, readFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { SCENARIOS, type Persona, type Scenario } from './scenarios.ts';

const args = process.argv.slice(2);
const flag = (name: string) => {
	const i = args.indexOf(name);
	return i === -1 ? undefined : args[i + 1];
};
const port = Number(flag('--port') ?? 4747);
const dir = flag('--dir') ?? join(homedir(), 'github', 'MacroHard');
/** In every message the agent gives when it couldn't finish a check (apps/agent/src/messages.ts). */
const unchecked = (text: string | undefined) => text !== undefined && /couldn't (?:be )?check/.test(text);

/** Each persona's folder in the MacroHard repo. */
const FOLDERS: Record<Persona, string> = {
	dev: 'James-May-Dev',
	pm: 'Richard-Hammond-PM',
	sales: 'Jeremy-Clarkson-Sales'
};

const PERSONA_TITLES: Record<Persona, string> = {
	dev: 'James May, backend engineer (`James-May-Dev`)',
	pm: 'Richard Hammond, product manager (`Richard-Hammond-PM`)',
	sales: 'Jeremy Clarkson, enterprise sales (`Jeremy-Clarkson-Sales`)'
};

/** `__FAKE_STRIPE_KEY__` → the fake key MacroHard's setup.sh wrote to James-May-Dev/.env. */
function fakeKeys(): Record<string, string> {
	const env: Record<string, string> = {};
	try {
		for (const line of readFileSync(join(dir, FOLDERS.dev, '.env'), 'utf8').split('\n')) {
			const m = /^([A-Z_]+)=(.*)$/.exec(line);
			if (m) env[m[1]!] = m[2]!;
		}
	} catch {
		// Not installed: placeholders stay as they are (only matters for the key scenarios).
	}
	return { __FAKE_STRIPE_KEY__: env['STRIPE_SECRET_KEY'] ?? '__FAKE_STRIPE_KEY__' };
}

function fill(text: string, keys: Record<string, string>): string {
	return text.replace(/__FAKE_[A-Z_]+__/g, (p) => keys[p] ?? p);
}

if (args.includes('--list')) {
	printGuide();
} else {
	process.exitCode = await runChecks();
}

function printGuide() {
	const out: string[] = [
		'# Try these',
		'',
		'Things each MacroHard person might do in Claude Code, and what Safe Context should do.',
		'Open their folder in Claude Code (terminal or desktop app) and type the prompt, or ask',
		'Claude to do what the "Claude reads" rows describe. Paths are relative to that folder.',
		'',
		'Rows marked ⚠️ show where Safe Context falls short today. They are worth trying too.',
		'',
		'Generated by `node demo/check.ts --list` from `demo/scenarios.ts` in the safecontext repo. Edit it there.',
		''
	];
	for (const persona of ['dev', 'pm', 'sales'] as const) {
		out.push(`## ${PERSONA_TITLES[persona]}`, '', '| What you do | Expected | Why |', '| --- | --- | --- |');
		for (const s of SCENARIOS.filter((x) => x.persona === persona)) {
			const what =
				s.kind === 'prompt'
					? `Type: “${s.text.replace('__FAKE_STRIPE_KEY__', '<the STRIPE_SECRET_KEY from .env>')}”`
					: describe(s).replace('__FAKE_STRIPE_KEY__', '<key>');
			const expected = {
				allow: '✅ goes through',
				block: '⛔ blocked',
				clean: '🧹 cleaned',
				unchanged: '✅ unchanged',
				restored: '🔁 real values put back',
				refused: '⛔ refused'
			}[s.expect];
			const why = s.gap ? `${s.why}<br>⚠️ **Known gap:** ${s.gap}` : s.why;
			out.push(`| ${what.replaceAll('|', '\\|')} | ${expected} | ${why.replaceAll('|', '\\|')} |`);
		}
		out.push('');
	}
	console.log(out.join('\n'));
}

function describe(s: Scenario): string {
	switch (s.kind) {
		case 'prompt':
			return s.text;
		case 'read':
			return `Claude reads \`${s.file}\``;
		case 'bash':
			return `Claude runs \`${s.command}\``;
		case 'write':
			return `Claude reads \`${s.file}\`, then writes \`${s.to}\` from it`;
		case 'open':
			return `Claude lists \`${s.folder}/\`, then opens \`${s.opens}\` by the name it saw`;
	}
}

async function post(path: string, body: unknown): Promise<Record<string, unknown>> {
	const res = await fetch(`http://127.0.0.1:${port}${path}`, {
		method: 'POST',
		headers: { 'content-type': 'application/json' },
		body: JSON.stringify(body),
		signal: AbortSignal.timeout(30_000)
	});
	if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
	return (await res.json()) as Record<string, unknown>;
}

async function run(s: Scenario, keys: Record<string, string>): Promise<{ got: string; detail?: string }> {
	const common = { session_id: `demo-${s.persona}`, cwd: join(dir, FOLDERS[s.persona]), transcript_path: '/dev/null' };
	const toolUseId = `toolu_demo_${Math.random().toString(36).slice(2, 12)}`;
	if (s.kind === 'prompt') {
		const out = await post('/v1/prompt', { ...common, hook_event_name: 'UserPromptSubmit', prompt: fill(s.text, keys) });
		const reason = out['reason'] as string | undefined;
		if (unchecked(reason)) return { got: 'check failed', detail: reason };
		return { got: out['decision'] === 'block' ? 'block' : 'allow', detail: reason };
	}
	if (s.kind === 'bash') {
		const out = await post('/v1/tool-input', {
			...common,
			hook_event_name: 'PreToolUse',
			tool_name: 'Bash',
			tool_input: { command: fill(s.command, keys) },
			tool_use_id: toolUseId
		});
		const hso = out['hookSpecificOutput'] as { permissionDecision?: string; permissionDecisionReason?: string } | undefined;
		const reason = hso?.permissionDecisionReason;
		if (unchecked(reason)) return { got: 'check failed', detail: reason };
		return { got: hso?.permissionDecision === 'deny' ? 'block' : 'allow', detail: reason };
	}
	const folder = join(dir, FOLDERS[s.persona]);
	const preTool = async (tool_name: string, tool_input: Record<string, unknown>) => {
		const out = await post('/v1/tool-input', {
			...common,
			hook_event_name: 'PreToolUse',
			tool_name,
			tool_input,
			tool_use_id: toolUseId
		});
		return out['hookSpecificOutput'] as
			| { permissionDecision?: string; permissionDecisionReason?: string; updatedInput?: Record<string, unknown> }
			| undefined;
	};

	if (s.kind === 'open') {
		// What `ls` shows Claude, then a Read of the name Claude saw.
		const names = readdirSync(join(folder, s.folder)).sort();
		const out = await post('/v1/tool-output', {
			...common,
			hook_event_name: 'PostToolUse',
			tool_name: 'Bash',
			tool_input: { command: `ls ${s.folder}` },
			tool_use_id: toolUseId,
			tool_response: { stdout: names.join('\n'), stderr: '', interrupted: false, isImage: false, noOutputExpected: false }
		});
		const updated = out['hookSpecificOutput'] as { updatedToolOutput?: { stdout?: string } } | undefined;
		const shown = updated?.updatedToolOutput?.stdout;
		if (shown === undefined) return { got: 'listing unchanged' };
		const seen = shown.split('\n')[names.indexOf(s.opens)] ?? '';
		const hso = await preTool('Read', { file_path: join(folder, s.folder, seen) });
		const opened = hso?.updatedInput?.['file_path'];
		const ok = opened === join(folder, s.folder, s.opens);
		return { got: ok ? 'restored' : `opened ${String(opened ?? seen)}`, detail: `Claude saw ${s.folder}/${seen}` };
	}

	const filePath = join(folder, s.file);
	const content = readFileSync(filePath, 'utf8');
	const out = await post('/v1/tool-output', {
		...common,
		hook_event_name: 'PostToolUse',
		tool_name: 'Read',
		tool_input: { file_path: filePath },
		tool_use_id: toolUseId,
		tool_response: {
			type: 'text',
			file: { filePath, content, numLines: content.split('\n').length, startLine: 1, totalLines: content.split('\n').length }
		}
	});
	const hso = out['hookSpecificOutput'] as { updatedToolOutput?: { file?: { content?: string } } } | undefined;
	const cleaned = hso?.updatedToolOutput?.file?.content;

	if (s.kind === 'write') {
		// Claude writes back every placeholder it saw (here: the whole cleaned file).
		if (cleaned === undefined || unchecked(cleaned)) return { got: 'nothing hidden to write back', detail: cleaned };
		const pre = await preTool('Write', { file_path: join(folder, s.to), content: cleaned });
		if (pre?.permissionDecision === 'deny') return { got: 'refused', detail: pre.permissionDecisionReason };
		const written = pre?.updatedInput?.['content'];
		if (typeof written !== 'string') return { got: 'placeholders written as they are' };
		const missing = (s.restores ?? []).filter((v) => !written.includes(v));
		return { got: missing.length ? `restored, but missing ${missing.join(', ')}` : 'restored' };
	}

	if (cleaned === undefined) return { got: 'unchanged' };
	if (unchecked(cleaned)) return { got: 'check failed', detail: cleaned };
	const leaked = (s.hides ?? []).filter((h) => cleaned.includes(h));
	return { got: leaked.length ? `clean, but leaked ${leaked.join(', ')}` : 'clean', detail: cleaned };
}

async function runChecks(): Promise<number> {
	const keys = fakeKeys();
	let failed = 0;
	for (const s of SCENARIOS) {
		const label = describe(s);
		const started = performance.now();
		let result: { got: string; detail?: string };
		try {
			result = await run(s, keys);
		} catch (err) {
			result = { got: `error: ${(err as Error).message}` };
		}
		const ms = Math.round(performance.now() - started);
		const ok = result.got === s.expect;
		if (!ok) failed++;
		console.log(`${ok ? 'ok  ' : 'FAIL'} [${s.persona}] ${fill(label, {}).slice(0, 90)} → ${result.got} (${ms} ms)`);
		if (!ok || args.includes('--verbose')) {
			if (result.detail) console.log(`       ${result.detail.replaceAll('\n', '\n       ')}`);
		}
	}
	console.log(`\n${SCENARIOS.length - failed}/${SCENARIOS.length} as expected`);
	return failed ? 1 : 0;
}
